<?php

declare(strict_types=1);

use PortLibs\Pandoc\AstNode;
use PortLibs\Pandoc\PandocConverter;

require __DIR__ . '/bootstrap.php';

ini_set('memory_limit', getenv('PANDOC_SAMPLE_REPORT_MEMORY_LIMIT') ?: '1024M');

$repoRoot = dirname(__DIR__);
$manifestPath = null;
$outputDir = $repoRoot . '/.upstream-cache/pandoc-reader-actual-output-report';
$pandocBin = getenv('PANDOC_BIN') ?: 'pandoc';
$limit = null;

foreach (array_slice($argv, 1) as $argument) {
    if ($argument === '--help' || $argument === '-h') {
        fwrite(STDOUT, <<<'TXT'
Usage: php tools/pandoc-reader-actual-output-report.php --manifest=PATH [--output-dir=PATH] [--pandoc-bin=PATH] [--limit=N]

Builds an HTML report containing the actual native/HTML output generated by
the local PHP Pandoc port and by an installed pandoc executable.

TXT);
        exit(0);
    }

    if (str_starts_with($argument, '--manifest=')) {
        $manifestPath = normalizePath($repoRoot, substr($argument, strlen('--manifest=')));
        continue;
    }

    if (str_starts_with($argument, '--output-dir=')) {
        $outputDir = normalizePath($repoRoot, substr($argument, strlen('--output-dir=')));
        continue;
    }

    if (str_starts_with($argument, '--pandoc-bin=')) {
        $pandocBin = substr($argument, strlen('--pandoc-bin='));
        if ($pandocBin === '') {
            fwrite(STDERR, "--pandoc-bin must not be empty\n");
            exit(2);
        }
        continue;
    }

    if (str_starts_with($argument, '--limit=')) {
        $rawLimit = substr($argument, strlen('--limit='));
        if (!ctype_digit($rawLimit) || (int) $rawLimit < 1) {
            fwrite(STDERR, "--limit must be a positive integer\n");
            exit(2);
        }
        $limit = (int) $rawLimit;
        continue;
    }

    fwrite(STDERR, "Unknown argument: {$argument}\n");
    exit(2);
}

if ($manifestPath === null) {
    fwrite(STDERR, "--manifest is required\n");
    exit(2);
}

$pandoc = resolveExecutable($pandocBin);
if ($pandoc === null) {
    fwrite(STDERR, "pandoc executable not found: {$pandocBin}\n");
    exit(1);
}

$report = buildActualOutputReport($repoRoot, $pandoc, $manifestPath, $outputDir, $limit);
writeFile($outputDir . '/index.html', renderReport($report));
writeFile(
    $outputDir . '/report.json',
    json_encode($report, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR) . "\n"
);

fwrite(STDOUT, "Wrote {$outputDir}/index.html\n");
fwrite(STDOUT, "Wrote {$outputDir}/report.json\n");
fwrite(STDOUT, summaryLine($report) . "\n");

/**
 * @return array<string, mixed>
 */
function buildActualOutputReport(
    string $repoRoot,
    string $pandoc,
    string $manifestPath,
    string $outputDir,
    ?int $limit
): array {
    if (!is_file($manifestPath)) {
        throw new RuntimeException("Manifest not found: {$manifestPath}");
    }
    $manifest = json_decode((string) file_get_contents($manifestPath), true, 512, JSON_THROW_ON_ERROR);
    if (!is_array($manifest) || !is_array($manifest['entries'] ?? null)) {
        throw new RuntimeException("Manifest must contain an entries array: {$manifestPath}");
    }

    ensureDirectory($outputDir . '/outputs');
    $entries = $manifest['entries'];
    if ($limit !== null) {
        $entries = array_slice($entries, 0, $limit);
    }

    $cases = [];
    foreach ($entries as $entry) {
        if (!is_array($entry)) {
            continue;
        }
        $cases[] = runCase($repoRoot, $pandoc, $outputDir, $entry);
    }

    return [
        'schemaVersion' => 1,
        'tool' => 'pandoc-reader-actual-output-report',
        'generatedAt' => gmdate('c'),
        'repoRoot' => $repoRoot,
        'manifestPath' => $manifestPath,
        'outputDir' => $outputDir,
        'pandocExecutable' => $pandoc,
        'pandocVersion' => pandocVersion($pandoc),
        'title' => (string) ($manifest['title'] ?? 'Pandoc reader actual output report'),
        'description' => (string) ($manifest['description'] ?? ''),
        'caseCount' => count($cases),
        'localNativeOkCount' => count(array_filter($cases, static fn (array $case): bool => $case['localNative']['ok'] === true)),
        'pandocNativeOkCount' => count(array_filter($cases, static fn (array $case): bool => $case['pandocNative']['ok'] === true)),
        'localHtmlOkCount' => count(array_filter($cases, static fn (array $case): bool => $case['localHtml']['ok'] === true)),
        'pandocHtmlOkCount' => count(array_filter($cases, static fn (array $case): bool => $case['pandocHtml']['ok'] === true)),
        'localWordPressOkCount' => count(array_filter($cases, static fn (array $case): bool => $case['localWordPress']['ok'] === true)),
        'cases' => $cases,
    ];
}

/**
 * @param array<string, mixed> $entry
 * @return array<string, mixed>
 */
function runCase(string $repoRoot, string $pandoc, string $outputDir, array $entry): array
{
    $format = (string) ($entry['format'] ?? '');
    $pandocFormat = (string) ($entry['pandocFormat'] ?? $format);
    $readerOptions = is_array($entry['readerOptions'] ?? null) ? $entry['readerOptions'] : [];
    $sourcePath = normalizePath($repoRoot, (string) ($entry['path'] ?? ''));
    $id = slug((string) ($entry['id'] ?? pathinfo($sourcePath, PATHINFO_FILENAME)));
    $caseDir = $outputDir . '/outputs/' . $id;
    ensureDirectory($caseDir);

    $case = [
        'id' => $id,
        'label' => (string) ($entry['id'] ?? $id),
        'format' => $format,
        'pandocFormat' => $pandocFormat,
        'readerOptions' => $readerOptions,
        'sourceFile' => relativePath($repoRoot, $sourcePath),
        'sourceUrl' => is_string($entry['sourceUrl'] ?? null) ? $entry['sourceUrl'] : null,
        'description' => (string) ($entry['description'] ?? ''),
        'features' => is_array($entry['features'] ?? null) ? array_values(array_map('strval', $entry['features'])) : [],
        'sourceBytes' => is_file($sourcePath) ? filesize($sourcePath) : null,
        'sourceSha256' => is_file($sourcePath) ? hash_file('sha256', $sourcePath) : null,
        'expectedSha256' => is_string($entry['sha256'] ?? null) ? $entry['sha256'] : null,
        'outputs' => [],
        'localParse' => ['ok' => false, 'error' => null],
        'localNative' => ['ok' => false, 'path' => null, 'error' => null],
        'pandocNative' => ['ok' => false, 'path' => null, 'error' => null],
        'localHtml' => ['ok' => false, 'path' => null, 'error' => null],
        'pandocHtml' => ['ok' => false, 'path' => null, 'error' => null],
        'localWordPress' => ['ok' => false, 'path' => null, 'error' => null],
    ];

    $document = null;
    if (!is_file($sourcePath)) {
        $case['localParse']['error'] = "Source file not found: {$sourcePath}";
    } else {
        try {
            $document = PandocConverter::readFile($sourcePath, $format, $readerOptions);
            $case['localParse'] = ['ok' => true, 'error' => null];
        } catch (Throwable $throwable) {
            $case['localParse']['error'] = exceptionSummary($throwable);
        }
    }

    if ($document instanceof AstNode) {
        $case['localNative'] = writeLocalOutput(
            $caseDir . '/local.native.txt',
            static fn (): string => PandocConverter::write($document, 'native', ['standalone' => true])
        );
        $case['localHtml'] = writeLocalOutput(
            $caseDir . '/local.html',
            static fn (): string => PandocConverter::write($document, 'html', ['writerHTMLMathMethod' => 'mathml'])
        );
        $case['localWordPress'] = writeLocalOutput(
            $caseDir . '/local-wordpress.html',
            static fn (): string => PandocConverter::write($document, 'wordpress', ['writerHTMLMathMethod' => 'mathml'])
        );
    }

    if (is_file($sourcePath)) {
        $case['pandocNative'] = writePandocOutput(
            $pandoc,
            ['-f', $pandocFormat, '-t', 'native', $sourcePath],
            $caseDir . '/pandoc.native.txt'
        );
        $case['pandocHtml'] = writePandocOutput(
            $pandoc,
            ['-f', $pandocFormat, '-t', 'html', '--standalone', $sourcePath],
            $caseDir . '/pandoc.html'
        );
    }

    foreach (['localNative', 'pandocNative', 'localHtml', 'pandocHtml', 'localWordPress'] as $key) {
        $path = $case[$key]['path'];
        if (is_string($path)) {
            $case[$key]['href'] = relativePath($outputDir, $path);
            $case['outputs'][$key] = [
                'path' => relativePath($outputDir, $path),
                'bytes' => filesize($path),
                'sha256' => hash_file('sha256', $path),
            ];
        }
    }

    writeFile($caseDir . '/case.json', json_encode($case, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR) . "\n");

    return $case;
}

/**
 * @return array{ok: bool, path: ?string, error: ?string}
 */
function writeLocalOutput(string $path, callable $callback): array
{
    try {
        $output = $callback();
        writeFile($path, $output);

        return ['ok' => true, 'path' => $path, 'error' => null];
    } catch (Throwable $throwable) {
        writeFile($path . '.error.txt', exceptionSummary($throwable) . "\n");

        return ['ok' => false, 'path' => $path . '.error.txt', 'error' => exceptionSummary($throwable)];
    }
}

/**
 * @param list<string> $arguments
 * @return array{ok: bool, path: ?string, error: ?string}
 */
function writePandocOutput(string $pandoc, array $arguments, string $path): array
{
    $result = runProcess(array_merge([$pandoc], $arguments));
    $body = $result['stdout'];
    if ($result['stderr'] !== '') {
        writeFile($path . '.stderr.txt', $result['stderr']);
    }
    if ($result['exitCode'] === 0) {
        writeFile($path, $body);

        return ['ok' => true, 'path' => $path, 'error' => $result['stderr'] === '' ? null : $result['stderr']];
    }

    $message = trim($result['stderr'] !== '' ? $result['stderr'] : $result['stdout']);
    if ($message === '') {
        $message = 'pandoc exited with status ' . $result['exitCode'];
    }
    writeFile($path . '.error.txt', $message . "\n");

    return ['ok' => false, 'path' => $path . '.error.txt', 'error' => $message];
}

/**
 * @param list<string> $command
 * @return array{stdout: string, stderr: string, exitCode: int}
 */
function runProcess(array $command): array
{
    $descriptors = [
        0 => ['pipe', 'r'],
        1 => ['pipe', 'w'],
        2 => ['pipe', 'w'],
    ];
    $process = proc_open(escapedCommand($command), $descriptors, $pipes);
    if (!is_resource($process)) {
        return ['stdout' => '', 'stderr' => 'proc_open failed', 'exitCode' => 127];
    }

    fclose($pipes[0]);
    $stdout = stream_get_contents($pipes[1]);
    $stderr = stream_get_contents($pipes[2]);
    fclose($pipes[1]);
    fclose($pipes[2]);
    $exitCode = proc_close($process);

    return [
        'stdout' => is_string($stdout) ? $stdout : '',
        'stderr' => is_string($stderr) ? $stderr : '',
        'exitCode' => is_int($exitCode) ? $exitCode : 1,
    ];
}

/**
 * @param list<string> $command
 */
function escapedCommand(array $command): string
{
    return implode(' ', array_map('escapeshellarg', $command));
}

