function summaryStat(string $label, string $value): string
{
    return '<div class="stat"><strong>' . h($value) . '</strong>' . h($label) . '</div>';
}

function okCount(array $report, string $key): string
{
    return (string) ($report[$key] ?? 0) . '/' . (string) ($report['caseCount'] ?? 0);
}

/**
 * @param array<string, mixed> $case
 */
function renderCase(array $case): string
{
    $links = [];
    foreach ([
        'localNative' => 'local native',
        'pandocNative' => 'pandoc native',
        'localHtml' => 'local HTML',
        'pandocHtml' => 'pandoc HTML',
        'localWordPress' => 'local WordPress',
    ] as $key => $label) {
        $output = $case['outputs'][$key] ?? null;
        if (is_array($output) && is_string($output['path'] ?? null)) {
            $links[] = '<a href="' . h(urlPath((string) $output['path'])) . '">' . h($label) . '</a>';
        }
    }

    $features = array_map(static fn (string $feature): string => '<span class="pill">' . h($feature) . '</span>', $case['features'] ?? []);
    $sourceUrl = is_string($case['sourceUrl'] ?? null)
        ? '<a href="' . h((string) $case['sourceUrl']) . '">' . h((string) $case['sourceUrl']) . '</a>'
        : h((string) $case['sourceFile']);

    return '<section class="case">'
        . '<div class="case-header">'
        . '<h2>' . h((string) $case['label']) . '</h2>'
        . '<div class="meta">'
        . '<span class="pill">' . h((string) $case['format']) . '</span>'
        . '<span class="pill">pandoc -f ' . h((string) $case['pandocFormat']) . '</span>'
        . '<span>' . h(number_format((int) ($case['sourceBytes'] ?? 0))) . ' bytes</span>'
        . '<span>source: ' . $sourceUrl . '</span>'
        . '</div>'
        . ($features === [] ? '' : '<div class="meta">' . implode('', $features) . '</div>')
        . '<div class="links">' . implode('', $links) . '</div>'
        . '</div>'
        . renderNativeComparison($case)
        . renderHtmlComparison($case)
        . renderWordPressOutput($case)
        . '</section>';
}

/**
 * @param array<string, mixed> $case
 */
function renderNativeComparison(array $case): string
{
    return '<details open><summary>Native AST output</summary>'
        . '<div class="compare">'
        . renderTextPanel('Local port native', $case['localNative'])
        . renderTextPanel('Pandoc native', $case['pandocNative'])
        . '</div></details>';
}

/**
 * @param array<string, mixed> $case
 */
function renderHtmlComparison(array $case): string
{
    return '<details><summary>Rendered HTML output</summary>'
        . '<div class="compare">'
        . renderFramePanel('Local port HTML', $case['localHtml'])
        . renderFramePanel('Pandoc HTML', $case['pandocHtml'])
        . '</div></details>';
}

/**
 * @param array<string, mixed> $case
 */
function renderWordPressOutput(array $case): string
{
    return '<details><summary>WordPress block output from local port</summary>'
        . '<div class="compare">'
        . renderTextPanel('Local WordPress blocks', $case['localWordPress'])
        . renderFramePanel('Rendered WordPress HTML/comments', $case['localWordPress'])
        . '</div></details>';
}

/**
 * @param array{ok: bool, path: ?string, href?: string, error: ?string} $result
 */
function renderTextPanel(string $title, array $result): string
{
    $class = $result['ok'] ? 'ok' : 'bad';
    $body = is_string($result['path'])
        ? previewFile($result['path'])
        : (string) ($result['error'] ?? 'No output file');

    return '<div class="panel"><div class="panel-title ' . $class . '">' . h($title) . '</div><pre' . ($result['ok'] ? '' : ' class="error"') . '>' . h($body) . '</pre></div>';
}

/**
 * @param array{ok: bool, path: ?string, href?: string, error: ?string} $result
 */
function renderFramePanel(string $title, array $result): string
{
    $class = $result['ok'] ? 'ok' : 'bad';
    if (!$result['ok'] || !is_string($result['path'])) {
        $body = is_string($result['path'])
            ? previewFile($result['path'])
            : (string) ($result['error'] ?? 'No output file');

        return '<div class="panel"><div class="panel-title ' . $class . '">' . h($title) . '</div><pre class="error">' . h($body) . '</pre></div>';
    }

    $href = is_string($result['href'] ?? null) ? (string) $result['href'] : basename($result['path']);

    return '<div class="panel"><div class="panel-title ok">' . h($title) . '</div><iframe src="' . h(urlPath($href)) . '"></iframe></div>';
}

function previewFile(string $path): string
{
    $bytes = file_get_contents($path, false, null, 0, 30000);
    if (!is_string($bytes)) {
        return 'Unable to read output preview.';
    }
    if (is_file($path) && filesize($path) > strlen($bytes)) {
        return $bytes . "\n\n[preview truncated; open the linked output file for the full content]";
    }

    return $bytes;
}

function writeFile(string $path, string $bytes): void
{
    ensureDirectory(dirname($path));
    if (file_put_contents($path, $bytes) === false) {
        throw new RuntimeException("Unable to write {$path}");
    }
}

function ensureDirectory(string $path): void
{
    if (!is_dir($path) && !mkdir($path, 0777, true) && !is_dir($path)) {
        throw new RuntimeException("Unable to create directory {$path}");
    }
}

function normalizePath(string $repoRoot, string $path): string
{
    if ($path === '') {
        return $repoRoot;
    }
    if ($path[0] === '/') {
        return $path;
    }

    return $repoRoot . '/' . $path;
}

function relativePath(string $base, string $path): string
{
    $base = rtrim($base, '/') . '/';
    if (str_starts_with($path, $base)) {
        return substr($path, strlen($base));
    }

    return $path;
}

function resolveExecutable(string $candidate): ?string
{
    if (str_contains($candidate, '/') && is_executable($candidate)) {
        return $candidate;
    }
    $result = runProcess(['/usr/bin/env', 'sh', '-lc', 'command -v ' . escapeshellarg($candidate)]);
    $path = trim($result['stdout']);
    if ($result['exitCode'] === 0 && $path !== '') {
        return $path;
    }

    return null;
}

function pandocVersion(string $pandoc): string
{
    $result = runProcess([$pandoc, '--version']);
    if ($result['exitCode'] !== 0) {
        return 'unknown';
    }
    $lines = preg_split('/\R/', trim($result['stdout']));

    return is_array($lines) && isset($lines[0]) ? $lines[0] : 'unknown';
}

function exceptionSummary(Throwable $throwable): string
{
    return get_class($throwable) . ': ' . $throwable->getMessage()
        . ' at ' . $throwable->getFile() . ':' . $throwable->getLine();
}

function summaryLine(array $report): string
{
    return 'Cases: ' . $report['caseCount']
        . '; local native: ' . $report['localNativeOkCount'] . '/' . $report['caseCount']
        . '; pandoc native: ' . $report['pandocNativeOkCount'] . '/' . $report['caseCount']
        . '; local HTML: ' . $report['localHtmlOkCount'] . '/' . $report['caseCount']
        . '; pandoc HTML: ' . $report['pandocHtmlOkCount'] . '/' . $report['caseCount']
        . '; local WordPress: ' . $report['localWordPressOkCount'] . '/' . $report['caseCount'];
}

function slug(string $value): string
{
    $slug = strtolower((string) preg_replace('/[^a-zA-Z0-9._-]+/', '-', trim($value)));
    $slug = trim($slug, '-._');

    return $slug === '' ? 'case' : $slug;
}

function h(string $value): string
{
    return htmlspecialchars($value, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
}

function urlPath(string $path): string
{
    return implode('/', array_map('rawurlencode', explode('/', $path)));
}
