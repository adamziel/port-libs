        $t->same(-2, $indexXinfo[0]['cid']);
        $t->same('key_fold', $indexXinfo[1]['name']);
        $t->same('NOCASE', $indexXinfo[1]['coll']);
        $t->same(1, $indexXinfo[1]['desc']);
    };
