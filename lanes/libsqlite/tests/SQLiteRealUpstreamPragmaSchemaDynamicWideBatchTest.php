foreach (range(1, 80) as $variant) {
    $tests["real upstream pragma schema wide batch pragma3 data-version external observer variant {$variant}"] = static function (TestRunner $t) use ($variant): void {
        $state = new SQLitePragmaSchemaDataVersion([
            'main' => ['schema_version' => 10 + $variant, 'data_version' => 1, 'change_counter' => 1, 'user_version' => 0],
            'aux' => ['schema_version' => 20 + $variant, 'data_version' => 3, 'change_counter' => 3, 'user_version' => $variant],
        ]);

        $before = $state->execute('PRAGMA main.data_version');
        $ignored = $state->execute('PRAGMA main.data_version = 9000');
        $state->recordLocalCommit('main', 2, 'local_pragma3_commit');
        $local = $state->execute('PRAGMA main.data_version');
        $state->recordExternalCommit('main', 1, 'external_pragma3_commit');
        $external = $state->execute('PRAGMA main.data_version');

        $t->same(1, $before['value']);
        $t->same(false, $ignored['changed']);
        $t->same('read_only_pragma_ignored', $ignored['reason']);
        $t->same(1, $local['value']);
        $t->same(2, $external['value']);
        $t->same(4, $state->headerUpdate('main')['file_change_counter']);
    };

    $tests["real upstream pragma schema wide batch pragma.test 8 schema user rollback variant {$variant}"] = static function (TestRunner $t) use ($variant): void {
        $state = new SQLitePragmaSchemaDataVersion([
            'main' => ['schema_version' => 100 + $variant, 'data_version' => 1, 'change_counter' => 1, 'user_version' => $variant],
            'aux' => ['schema_version' => 200 + $variant, 'data_version' => 1, 'change_counter' => 1, 'user_version' => 10 + $variant],
        ]);

        $state->beginTransaction();
        $state->execute('PRAGMA main.user_version = ' . (300 + $variant));
        $state->execute('PRAGMA aux.schema_version = ' . (400 + $variant));
        $duringMain = $state->execute('PRAGMA user_version')['value'];
        $duringAux = $state->execute('PRAGMA aux.schema_version')['value'];
        $state->rollbackTransaction();

        $t->same(300 + $variant, $duringMain);
        $t->same(400 + $variant, $duringAux);
        $t->same($variant, $state->execute('PRAGMA main.user_version')['value']);
        $t->same(200 + $variant, $state->execute('PRAGMA aux.schema_version')['value']);
    };
}

