$tests = [];

$valueAt = static function (array $value, string $path): mixed {
    $current = $value;
    foreach (explode('.', $path) as $part) {
        if ($part === 'count') {
            $current = count($current);
            continue;
        }
        $current = is_numeric($part) ? $current[(int) $part] : $current[$part];
    }

    return $current;
};

foreach (range(1, 250) as $variant) {
    $parent = 'pragma_wide_parent_' . $variant;
    $child = 'pragma_wide_child_' . $variant;
    $generated = 'pragma_wide_generated_' . $variant;
    $index = 'pragma_wide_child_' . $variant . '_lookup';
    $partial = 'pragma_wide_generated_' . $variant . '_partial';
    $autoParent = 'sqlite_autoindex_' . $parent . '_1';
    $autoChild = 'sqlite_autoindex_' . $child . '_1';
    $autoGenerated = 'sqlite_autoindex_' . $generated . '_1';

    $catalog = static function () use ($variant, $parent, $child, $generated, $index, $partial, $autoParent, $autoChild, $autoGenerated): SQLitePragmaSchemaCatalog {
        return new SQLitePragmaSchemaCatalog([
            new SQLiteSchemaRecord(
                'table',
                $parent,
                $parent,
                1000 + $variant,
                "CREATE TABLE {$parent}(
                    tenant_id INTEGER NOT NULL,
                    key_name TEXT NOT NULL DEFAULT 'key_{$variant}',
                    region TEXT DEFAULT 'region_{$variant}',
                    PRIMARY KEY(tenant_id, key_name)
                ) WITHOUT ROWID",
                2000 + $variant,
            ),
            new SQLiteSchemaRecord('index', $autoParent, $parent, 3000 + $variant, null, 3000 + $variant),
            new SQLiteSchemaRecord(
                'table',
                $child,
                $child,
                4000 + $variant,
                "CREATE TABLE {$child}(
                    tenant_id INTEGER NOT NULL,
                    key_name TEXT NOT NULL,
                    payload TEXT DEFAULT (json_object('variant',{$variant})),
                    load_policy TEXT DEFAULT 'lazy',
                    UNIQUE(key_name, tenant_id),
                    FOREIGN KEY(tenant_id, key_name) REFERENCES {$parent}(tenant_id, key_name) ON UPDATE CASCADE ON DELETE RESTRICT
                )",
                5000 + $variant,
            ),
            new SQLiteSchemaRecord('index', $autoChild, $child, 6000 + $variant, null, 6000 + $variant),
            new SQLiteSchemaRecord('index', $index, $child, 7000 + $variant, "CREATE INDEX {$index} ON {$child}(load_policy COLLATE nocase DESC, key_name ASC)", 7000 + $variant),
            new SQLiteSchemaRecord(
                'table',
                $generated,
                $generated,
                8000 + $variant,
                "CREATE TABLE {$generated}(
                    id INTEGER PRIMARY KEY,
                    key_name TEXT NOT NULL DEFAULT 'generated_{$variant}',
                    key_fold TEXT GENERATED ALWAYS AS (lower(key_name)) VIRTUAL,
                    key_len INTEGER GENERATED ALWAYS AS (length(key_name)) STORED,
                    UNIQUE(key_name)
                )",
                9000 + $variant,
            ),
            new SQLiteSchemaRecord('index', $autoGenerated, $generated, 10000 + $variant, null, 10000 + $variant),
            new SQLiteSchemaRecord('index', $partial, $generated, 11000 + $variant, "CREATE INDEX {$partial} ON {$generated}((length(key_name)), key_fold DESC COLLATE nocase) WHERE key_name IS NOT NULL", 11000 + $variant),
        ]);
    };

