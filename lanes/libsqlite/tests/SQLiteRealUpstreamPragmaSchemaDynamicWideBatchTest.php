        $t->same("json_object('variant',{$variant})", $rows[2]['dflt_value']);
        $t->same('load_policy', $rows[3]['name']);
        $t->same("'lazy'", $rows[3]['dflt_value']);
    };

    $tests["real upstream pragma schema wide batch pragma4 4.3-4.4 index metadata variant {$variant}"] = static function (TestRunner $t) use ($catalog, $child, $index, $autoChild): void {
