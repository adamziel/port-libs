    $tests["real upstream pragma schema wide batch pragma4 4.5 foreign-key and 6.0 table-list variant {$variant}"] = static function (TestRunner $t) use ($catalog, $parent, $child): void {
        $catalog = $catalog();
        $foreignKeys = $catalog->executeTableValuedPragma("pragma_foreign_key_list('{$child}')")['rows'];
