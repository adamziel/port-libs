<?php

declare(strict_types=1);

namespace PortLibs\Pandoc;

final class EpubExecutableNativeAstComparisonHarness
{
    private const DEFAULT_MAX_EXAMPLES = 12;
    private const VERDICT = 'pandoc-executable-normalized-ast-comparison-not-full-epub-parity';
    private const CLAIM = 'Compares local PHP EPUB reader output, native output generated by a local pandoc executable, and paired checked-in .native goldens using the EPUB normalized AST policy; this is executable golden-fixture evidence and does not assert that the upstream Haskell/Tasty process itself was run.';

    /**
     * @param array{limit?: int, maxExamples?: int, pandocBin?: string} $options
     * @return array<string, mixed>
     */
    public function run(string $epubDirectory, array $options = []): array
    {
        $limit = max(0, (int) ($options['limit'] ?? 0));
        $maxExamples = max(0, (int) ($options['maxExamples'] ?? self::DEFAULT_MAX_EXAMPLES));

        if (!is_dir($epubDirectory)) {
            return $this->skippedReport($epubDirectory, null, 'epub-directory-missing');
        }

        $pandoc = $this->resolvePandocBin(is_string($options['pandocBin'] ?? null) ? (string) $options['pandocBin'] : null);
        if ($pandoc === null) {
            return $this->skippedReport($epubDirectory, is_string($options['pandocBin'] ?? null) ? (string) $options['pandocBin'] : null, 'pandoc-executable-missing');
        }

        $epubFiles = $this->filesByBasename($epubDirectory, 'epub');
        $nativeFiles = $this->filesByBasename($epubDirectory, 'native');
        $fixtureNames = array_keys($epubFiles);
        sort($fixtureNames, SORT_STRING);
        $totalEpubCount = count($fixtureNames);
        if ($limit > 0) {
            $fixtureNames = array_slice($fixtureNames, 0, $limit);
        }

        $localParsedCount = 0;
        $pandocParsedCount = 0;
        $nativeFixtureParsedCount = 0;
        $bothParsedCount = 0;
        $matchCount = 0;
        $pandocNativeFixtureComparedCount = 0;
        $pandocNativeFixtureMatchCount = 0;
        $pandocNativeFixtureByteComparedCount = 0;
        $pandocNativeFixtureByteMatchCount = 0;
        $parseFailures = [];
        $mismatches = [];
        $nativeFixtureMismatches = [];
        $nativeFixtureByteMismatches = [];
        $categoryCounts = [];
        $normalizer = new EpubNativeAstPackageComparisonHarness();

        foreach ($fixtureNames as $fixtureName) {
            $localResult = $this->readLocalEpub($epubFiles[$fixtureName]);
            if ($localResult['ok']) {
                ++$localParsedCount;
            }

            $pandocResult = $this->readPandocNative($pandoc, $epubFiles[$fixtureName]);
            if ($pandocResult['ok']) {
                ++$pandocParsedCount;
            }

            $nativeFixtureResult = $this->readNativeFixture($nativeFiles[$fixtureName] ?? null);
            if ($nativeFixtureResult['ok']) {
                ++$nativeFixtureParsedCount;
            }

            if (!$localResult['ok'] || !$pandocResult['ok'] || !$nativeFixtureResult['ok']) {
                $parseFailures[] = [
                    'fixture' => $fixtureName,
                    'localError' => $localResult['error'],
                    'pandocError' => $pandocResult['error'],
                    'nativeFixtureError' => $nativeFixtureResult['error'],
                ];
                $this->addCategory($categoryCounts, 'parse-failure', $fixtureName, $maxExamples);
            }

            if ($localResult['ok'] && $pandocResult['ok']) {
                /** @var AstNode $localDocument */
                $localDocument = $localResult['document'];
                /** @var AstNode $pandocDocument */
                $pandocDocument = $pandocResult['document'];
                ++$bothParsedCount;

                $localAst = $normalizer->normalizedDocument($localDocument);
                $pandocAst = $normalizer->normalizedDocument($pandocDocument);
                if ($localAst === $pandocAst) {
                    ++$matchCount;
                } else {
                    $difference = $this->firstDifference($localAst, $pandocAst) ?? 'unknown-normalized-ast-difference';
                    $categories = $this->mismatchCategories($difference);
                    foreach ($categories as $category) {
                        $this->addCategory($categoryCounts, $category, $fixtureName, $maxExamples);
                    }

                    if (count($mismatches) < $maxExamples) {
                        $mismatches[] = [
                            'fixture' => $fixtureName,
                            'firstDifference' => $difference,
                            'categories' => $categories,
                            'localTopTypes' => $this->topTypeSequence($localDocument),
                            'pandocTopTypes' => $this->topTypeSequence($pandocDocument),
                        ];
                    }
                }
            }

            if ($nativeFixtureResult['ok'] && $pandocResult['ok']) {
                /** @var AstNode $nativeFixtureDocument */
                $nativeFixtureDocument = $nativeFixtureResult['document'];
                /** @var AstNode $pandocDocument */
                $pandocDocument = $pandocResult['document'];
                ++$pandocNativeFixtureComparedCount;

                $nativeFixtureAst = $normalizer->normalizedDocument($nativeFixtureDocument);
                $pandocAst = $normalizer->normalizedDocument($pandocDocument);
                if ($nativeFixtureAst === $pandocAst) {
                    ++$pandocNativeFixtureMatchCount;
                } else {
                    $difference = $this->firstDifference($nativeFixtureAst, $pandocAst) ?? 'unknown-checked-in-native-fixture-difference';
                    $categories = $this->mismatchCategories($difference);
                    $this->addCategory($categoryCounts, 'checked-in-native-fixture-drift', $fixtureName, $maxExamples);
                    foreach ($categories as $category) {
                        $this->addCategory($categoryCounts, $category, $fixtureName, $maxExamples);
                    }

                    if (count($nativeFixtureMismatches) < $maxExamples) {
                        $nativeFixtureMismatches[] = [
                            'fixture' => $fixtureName,
                            'firstDifference' => $difference,
                            'categories' => $categories,
                            'nativeFixtureTopTypes' => $this->topTypeSequence($nativeFixtureDocument),
                            'pandocTopTypes' => $this->topTypeSequence($pandocDocument),
                        ];
                    }
                }
            }

            if (is_string($nativeFixtureResult['native']) && is_string($pandocResult['native'])) {
                ++$pandocNativeFixtureByteComparedCount;

                if ($nativeFixtureResult['native'] === $pandocResult['native']) {
                    ++$pandocNativeFixtureByteMatchCount;
                } elseif (count($nativeFixtureByteMismatches) < $maxExamples) {
                    $nativeFixtureByteMismatches[] = [
                        'fixture' => $fixtureName,
                        'nativeFixtureSha256' => hash('sha256', $nativeFixtureResult['native']),
                        'pandocNativeSha256' => hash('sha256', $pandocResult['native']),
                        'nativeFixtureBytes' => strlen($nativeFixtureResult['native']),
                        'pandocNativeBytes' => strlen($pandocResult['native']),
                    ];
                }
            }
        }

        ksort($categoryCounts, SORT_STRING);
        $comparedEpubCount = count($fixtureNames);
        $mismatchCount = $bothParsedCount - $matchCount;
        $nativeFixtureMismatchCount = $pandocNativeFixtureComparedCount - $pandocNativeFixtureMatchCount;
        $nativeFixtureByteMismatchCount = $pandocNativeFixtureByteComparedCount - $pandocNativeFixtureByteMatchCount;

        return [
            'schemaVersion' => 1,
            'tool' => 'pandoc-epub-executable-native-ast',
            'status' => 'completed',
            'skipped' => false,
            'reason' => null,
            'verdict' => self::VERDICT,
            'claim' => self::CLAIM,
            'evidenceKind' => 'epub-pandoc-executable-normalized-ast-comparison',
            'epubDirectory' => $epubDirectory,
            'pandocExecutable' => $pandoc,
            'pandocVersion' => $this->pandocVersion($pandoc),
            'normalizationPolicy' => EpubNativeAstPackageComparisonHarness::class . '::normalizedDocument',
            'totalEpubCount' => $totalEpubCount,
            'comparedEpubCount' => $comparedEpubCount,
            'localParsedCount' => $localParsedCount,
            'pandocParsedCount' => $pandocParsedCount,
            'nativeFixtureParsedCount' => $nativeFixtureParsedCount,
            'bothParsedCount' => $bothParsedCount,
            'parseFailureCount' => count($parseFailures),
            'normalizedAstMatchCount' => $matchCount,
            'normalizedAstMismatchCount' => $mismatchCount,
            'normalizedAstMatchPercent' => self::percent($matchCount, $comparedEpubCount),
            'pandocNativeFixtureComparedCount' => $pandocNativeFixtureComparedCount,
            'pandocNativeFixtureMatchCount' => $pandocNativeFixtureMatchCount,
            'pandocNativeFixtureMismatchCount' => $nativeFixtureMismatchCount,
            'pandocNativeFixtureMatchPercent' => self::percent($pandocNativeFixtureMatchCount, $comparedEpubCount),
            'pandocNativeFixtureByteComparedCount' => $pandocNativeFixtureByteComparedCount,
            'pandocNativeFixtureByteMatchCount' => $pandocNativeFixtureByteMatchCount,
            'pandocNativeFixtureByteMismatchCount' => $nativeFixtureByteMismatchCount,
            'pandocNativeFixtureByteMatchPercent' => self::percent($pandocNativeFixtureByteMatchCount, $comparedEpubCount),
            'astParityStatus' => self::astParityStatus(count($parseFailures), $mismatchCount, $nativeFixtureMismatchCount, $comparedEpubCount),
            'parseFailures' => array_slice($parseFailures, 0, $maxExamples),
            'mismatchComparisons' => $mismatches,
            'pandocNativeFixtureMismatchComparisons' => $nativeFixtureMismatches,
            'pandocNativeFixtureByteMismatchComparisons' => $nativeFixtureByteMismatches,
            'mismatchCategories' => array_values($categoryCounts),
            'orderedRemainingGaps' => self::orderedRemainingGaps(
                true,
                true,
                $comparedEpubCount,
                count($parseFailures),
                $matchCount,
                $mismatchCount,
                $pandocNativeFixtureMatchCount,
                $nativeFixtureMismatchCount,
                $pandocNativeFixtureByteMatchCount,
                $nativeFixtureByteMismatchCount
            ),
        ];
    }

    /**
     * @param array<string, mixed> $report
     */
    public function formatReport(array $report): string
    {
        $lines = [
            'Pandoc EPUB executable/native AST comparison: ' . (string) ($report['status'] ?? 'unknown'),
            'Verdict: ' . (string) ($report['verdict'] ?? self::VERDICT),
            'Claim: ' . (string) ($report['claim'] ?? self::CLAIM),
            'epubDirectory=' . (string) ($report['epubDirectory'] ?? ''),
            'pandocExecutable=' . (string) ($report['pandocExecutable'] ?? ''),
        ];

        if (($report['skipped'] ?? false) === true) {
            $lines[] = 'reason=' . (string) ($report['reason'] ?? 'unknown');
            $lines = self::appendOrderedRemainingGaps($lines, $report);

            return implode(PHP_EOL, $lines) . PHP_EOL;
        }

        $lines[] = sprintf(
            'epub: total=%d compared=%d parsedBoth=%d parseFailures=%d nativeFixturesParsed=%d',
            (int) ($report['totalEpubCount'] ?? 0),
            (int) ($report['comparedEpubCount'] ?? 0),
            (int) ($report['bothParsedCount'] ?? 0),
            (int) ($report['parseFailureCount'] ?? 0),
            (int) ($report['nativeFixtureParsedCount'] ?? 0),
        );
        $lines[] = sprintf(
            'normalizedAst: matches=%d (%s) mismatches=%d status=%s',
            (int) ($report['normalizedAstMatchCount'] ?? 0),
            self::formatPercent($report['normalizedAstMatchPercent'] ?? null),
            (int) ($report['normalizedAstMismatchCount'] ?? 0),
            (string) ($report['astParityStatus'] ?? 'unknown'),
        );
        $lines[] = sprintf(
            'checkedInNativeFixture: pandocCompared=%d pandocMatches=%d (%s) pandocMismatches=%d',
            (int) ($report['pandocNativeFixtureComparedCount'] ?? 0),
            (int) ($report['pandocNativeFixtureMatchCount'] ?? 0),
            self::formatPercent($report['pandocNativeFixtureMatchPercent'] ?? null),
            (int) ($report['pandocNativeFixtureMismatchCount'] ?? 0),
        );
        $lines[] = sprintf(
            'checkedInNativeFixtureBytes: pandocCompared=%d pandocByteMatches=%d (%s) pandocByteMismatches=%d',
            (int) ($report['pandocNativeFixtureByteComparedCount'] ?? 0),
            (int) ($report['pandocNativeFixtureByteMatchCount'] ?? 0),
            self::formatPercent($report['pandocNativeFixtureByteMatchPercent'] ?? null),
            (int) ($report['pandocNativeFixtureByteMismatchCount'] ?? 0),
        );

        $mismatches = $report['mismatchComparisons'] ?? [];
        if (is_array($mismatches) && $mismatches !== []) {
            $lines[] = 'mismatchExamples:';
            foreach ($mismatches as $mismatch) {
                if (!is_array($mismatch)) {
                    continue;
                }
                $lines[] = '- ' . (string) ($mismatch['fixture'] ?? 'unknown')
                    . ': ' . (string) ($mismatch['firstDifference'] ?? 'unknown');
            }
        }
        $nativeFixtureMismatches = $report['pandocNativeFixtureMismatchComparisons'] ?? [];
        if (is_array($nativeFixtureMismatches) && $nativeFixtureMismatches !== []) {
            $lines[] = 'checkedInNativeFixtureMismatchExamples:';
            foreach ($nativeFixtureMismatches as $mismatch) {
                if (!is_array($mismatch)) {
                    continue;
                }
                $lines[] = '- ' . (string) ($mismatch['fixture'] ?? 'unknown')
                    . ': ' . (string) ($mismatch['firstDifference'] ?? 'unknown');
            }
        }
        $nativeFixtureByteMismatches = $report['pandocNativeFixtureByteMismatchComparisons'] ?? [];
        if (is_array($nativeFixtureByteMismatches) && $nativeFixtureByteMismatches !== []) {
            $lines[] = 'checkedInNativeFixtureByteMismatchExamples:';
            foreach ($nativeFixtureByteMismatches as $mismatch) {
                if (!is_array($mismatch)) {
                    continue;
                }
                $lines[] = sprintf(
                    '- %s: fixtureBytes=%d pandocBytes=%d fixtureSha256=%s pandocSha256=%s',
                    (string) ($mismatch['fixture'] ?? 'unknown'),
                    (int) ($mismatch['nativeFixtureBytes'] ?? 0),
                    (int) ($mismatch['pandocNativeBytes'] ?? 0),
                    (string) ($mismatch['nativeFixtureSha256'] ?? ''),
                    (string) ($mismatch['pandocNativeSha256'] ?? ''),
                );
            }
        }

        $lines = self::appendOrderedRemainingGaps($lines, $report);

        return implode(PHP_EOL, $lines) . PHP_EOL;
    }

    /**
     * @param array<string, mixed> $report
     */
    public static function hasRequiredExecutableParity(array $report, int $requiredEpubCount): bool
    {
        if ($requiredEpubCount < 0) {
            throw new \InvalidArgumentException('Required EPUB count must not be negative');
        }

        return ($report['skipped'] ?? false) === false
            && ($report['status'] ?? null) === 'completed'
            && (int) ($report['totalEpubCount'] ?? -1) === $requiredEpubCount
            && (int) ($report['comparedEpubCount'] ?? -1) === $requiredEpubCount
            && (int) ($report['localParsedCount'] ?? -1) === $requiredEpubCount
            && (int) ($report['pandocParsedCount'] ?? -1) === $requiredEpubCount
            && (int) ($report['nativeFixtureParsedCount'] ?? -1) === $requiredEpubCount
            && (int) ($report['bothParsedCount'] ?? -1) === $requiredEpubCount
            && (int) ($report['parseFailureCount'] ?? -1) === 0
            && (int) ($report['normalizedAstMatchCount'] ?? -1) === $requiredEpubCount
            && (int) ($report['normalizedAstMismatchCount'] ?? -1) === 0
            && (int) ($report['pandocNativeFixtureComparedCount'] ?? -1) === $requiredEpubCount
            && (int) ($report['pandocNativeFixtureMatchCount'] ?? -1) === $requiredEpubCount
            && (int) ($report['pandocNativeFixtureMismatchCount'] ?? -1) === 0
            && ($report['astParityStatus'] ?? null) === 'normalized-ast-equality-observed-against-pandoc-executable';
    }

    /**
     * @param array<string, mixed> $report
     */
    public static function hasRequiredPandocVersion(array $report, string $requiredPandocVersion): bool
    {
        if ($requiredPandocVersion === '') {
            throw new \InvalidArgumentException('Required Pandoc version must not be empty');
        }

        return ($report['skipped'] ?? false) === false
            && ($report['status'] ?? null) === 'completed'
            && ($report['pandocVersion'] ?? null) === $requiredPandocVersion;
    }

