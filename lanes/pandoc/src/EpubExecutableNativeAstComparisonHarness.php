    private function resolvePandocBin(?string $requested): ?string
    {
        $candidate = $requested;
        if ($candidate === null || $candidate === '') {
            $env = getenv('PANDOC_BIN');
            $candidate = is_string($env) && $env !== '' ? $env : 'pandoc';
        }

        if (str_contains($candidate, DIRECTORY_SEPARATOR)) {
            return is_file($candidate) && is_executable($candidate) ? $candidate : null;
        }

        $output = [];
        $exitCode = 0;
        exec('command -v ' . escapeshellarg($candidate) . ' 2>/dev/null', $output, $exitCode);
        if ($exitCode !== 0 || !is_string($output[0] ?? null) || trim($output[0]) === '') {
            return null;
        }

        return trim($output[0]);
    }

    /**
     * @return array<string, string>
     */
    private function filesByBasename(string $directory, string $extension): array
    {
        $files = [];
        foreach (glob(rtrim($directory, DIRECTORY_SEPARATOR) . DIRECTORY_SEPARATOR . '*.' . $extension) ?: [] as $path) {
            $files[basename($path, '.' . $extension)] = $path;
        }
        ksort($files, SORT_STRING);

        return $files;
    }

    /**
     * @return array{ok: bool, document: ?AstNode, error: ?string}
     */
    private function readLocalEpub(string $path): array
    {
        try {
            return ['ok' => true, 'document' => (new EpubReader())->readEpubFile($path), 'error' => null];
        } catch (\Throwable $exception) {
            return ['ok' => false, 'document' => null, 'error' => $exception::class . ': ' . $exception->getMessage()];
        }
    }

    /**
     * @return array{ok: bool, document: ?AstNode, native: ?string, error: ?string}
     */
    private function readNativeFixture(?string $path): array
    {
        if ($path === null) {
            return ['ok' => false, 'document' => null, 'native' => null, 'error' => 'missing paired .native fixture'];
        }

        try {
            $native = file_get_contents($path);
            if (!is_string($native)) {
                throw new \RuntimeException("Unable to read native fixture '{$path}'.");
            }

            return ['ok' => true, 'document' => (new NativeReader())->read($native), 'native' => $native, 'error' => null];
        } catch (\Throwable $exception) {
            return [
                'ok' => false,
                'document' => null,
                'native' => isset($native) && is_string($native) ? $native : null,
                'error' => $exception::class . ': ' . $exception->getMessage(),
            ];
        }
    }

    /**
     * @return array{ok: bool, document: ?AstNode, native: ?string, error: ?string}
     */
    private function readPandocNative(string $pandoc, string $epubPath): array
    {
        $result = $this->runProcess(
            escapeshellarg($pandoc)
            . ' -f epub -t native '
            . escapeshellarg($epubPath)
        );
        if ($result['exitCode'] !== 0) {
            return [
                'ok' => false,
                'document' => null,
                'native' => $result['stdout'] !== '' ? $result['stdout'] : null,
                'error' => 'pandoc exited ' . $result['exitCode'] . ': ' . trim($result['stderr']),
            ];
        }

        try {
            return ['ok' => true, 'document' => (new NativeReader())->read($result['stdout']), 'native' => $result['stdout'], 'error' => null];
        } catch (\Throwable $exception) {
            return ['ok' => false, 'document' => null, 'native' => $result['stdout'], 'error' => $exception::class . ': ' . $exception->getMessage()];
        }
    }

    private function pandocVersion(string $pandoc): ?string
    {
        $result = $this->runProcess(escapeshellarg($pandoc) . ' --version');
        if ($result['exitCode'] !== 0) {
            return null;
        }

        $lines = preg_split('/\R/', trim($result['stdout']));

        return is_array($lines) && is_string($lines[0] ?? null) && $lines[0] !== '' ? $lines[0] : null;
    }

    /**
     * @return array{exitCode: int, stdout: string, stderr: string}
     */
    private function runProcess(string $command): array
    {
        $process = proc_open($command, [
            0 => ['pipe', 'r'],
            1 => ['pipe', 'w'],
            2 => ['pipe', 'w'],
        ], $pipes);
        if (!is_resource($process)) {
            return ['exitCode' => 127, 'stdout' => '', 'stderr' => 'Unable to start process'];
        }

        fclose($pipes[0]);
        $stdout = stream_get_contents($pipes[1]);
        fclose($pipes[1]);
        $stderr = stream_get_contents($pipes[2]);
        fclose($pipes[2]);
        $exitCode = proc_close($process);

        return [
            'exitCode' => is_int($exitCode) ? $exitCode : 1,
            'stdout' => is_string($stdout) ? $stdout : '',
            'stderr' => is_string($stderr) ? $stderr : '',
        ];
    }

    private function firstDifference(mixed $local, mixed $pandoc, string $path = 'root'): ?string
    {
        if (gettype($local) !== gettype($pandoc)) {
            return "{$path} type " . gettype($local) . ' vs ' . gettype($pandoc);
        }
        if (!is_array($local)) {
            return $local === $pandoc ? null : "{$path} value " . self::shortJson($local) . ' vs ' . self::shortJson($pandoc);
        }

        $localKeys = array_keys($local);
        $pandocKeys = array_keys($pandoc);
        if ($localKeys !== $pandocKeys) {
            return "{$path} keys " . self::shortJson($localKeys) . ' vs ' . self::shortJson($pandocKeys);
        }

        foreach ($localKeys as $key) {
            $difference = $this->firstDifference($local[$key], $pandoc[$key], $path . '.' . $key);
            if ($difference !== null) {
                return $difference;
            }
        }

        return null;
    }

    /**
     * @return list<string>
     */
    private function mismatchCategories(string $difference): array
    {
        $lower = strtolower($difference);
        $categories = [];
        if (str_contains($lower, '.children keys')) {
            $categories[] = 'child-count-or-inline-granularity';
        }
        if (str_contains($lower, '.attrs keys') || str_contains($lower, '.attrs.')) {
            $categories[] = 'attribute-shape';
        }
        if (str_contains($lower, 'table') || str_contains($lower, 'row') || str_contains($lower, 'cell')) {
            $categories[] = 'table-shape';
        }
        if (str_contains($lower, 'image') || str_contains($lower, 'url') || str_contains($lower, 'alt')) {
            $categories[] = 'image-shape';
        }
        if (str_contains($lower, 'link') || str_contains($lower, 'href')) {
            $categories[] = 'link-shape';
        }
        if (str_contains($lower, 'math')) {
            $categories[] = 'math-shape';
        }
        if (str_contains($lower, '.type')) {
            $categories[] = 'node-type';
        }
        if (str_contains($lower, ' value ')) {
            $categories[] = 'scalar-value';
        }
        if ($categories === []) {
            $categories[] = 'uncategorized-normalized-ast-drift';
        }

        return array_values(array_unique($categories));
    }

    /**
     * @return list<string>
     */
    private function topTypeSequence(AstNode $document): array
    {
        return array_map(static fn (AstNode $child): string => $child->type, $document->children);
    }

    /**
     * @param array<string, array{category: string, count: int, examples: list<string>}> $categoryCounts
     */
    private function addCategory(array &$categoryCounts, string $category, string $fixture, int $maxExamples): void
    {
        if (!isset($categoryCounts[$category])) {
            $categoryCounts[$category] = ['category' => $category, 'count' => 0, 'examples' => []];
        }

        ++$categoryCounts[$category]['count'];
        if (count($categoryCounts[$category]['examples']) < $maxExamples) {
            $categoryCounts[$category]['examples'][] = $fixture;
        }
    }

    private static function astParityStatus(
        int $parseFailureCount,
        int $mismatchCount,
        int $nativeFixtureMismatchCount,
        int $comparedEpubCount
    ): string {
        if ($comparedEpubCount === 0) {
            return 'not-evaluated-no-epub-files';
        }
        if ($parseFailureCount > 0) {
            return 'blocked-by-parse-failures';
        }
        if ($mismatchCount > 0 || $nativeFixtureMismatchCount > 0) {
            return 'normalized-ast-mismatches-observed';
        }

        return 'normalized-ast-equality-observed-against-pandoc-executable';
    }

    /**
     * @return list<array<string, mixed>>
     */
    private static function orderedRemainingGaps(
        bool $directoryPresent,
        bool $executablePresent,
        int $comparedEpubCount,
        int $parseFailureCount,
        int $matchCount,
        int $mismatchCount,
        int $nativeFixtureMatchCount = 0,
        int $nativeFixtureMismatchCount = 0,
        int $nativeFixtureByteMatchCount = 0,
        int $nativeFixtureByteMismatchCount = 0
    ): array {
        if (!$directoryPresent) {
            $sourceEvidence = 'EPUB directory absent; executable comparison did not run';
        } elseif (!$executablePresent) {
            $sourceEvidence = 'pandoc executable absent; executable comparison did not run';
        } else {
            $sourceEvidence = "compared epubs={$comparedEpubCount}; parse failures={$parseFailureCount}; local/executable normalized AST matches={$matchCount}; local/executable normalized AST mismatches={$mismatchCount}; executable/checked-in-native matches={$nativeFixtureMatchCount}; executable/checked-in-native mismatches={$nativeFixtureMismatchCount}; executable/checked-in-native byte matches={$nativeFixtureByteMatchCount}; executable/checked-in-native byte mismatches={$nativeFixtureByteMismatchCount}";
        }

        $executableEvidenceCovered = $parseFailureCount === 0
            && $mismatchCount === 0
            && $nativeFixtureMismatchCount === 0
            && $comparedEpubCount > 0
            && $matchCount === $comparedEpubCount
            && $nativeFixtureMatchCount === $comparedEpubCount;

        return [
            [
                'rank' => 1,
                'id' => 'pandoc-executable-epub-native-ast-equality',
                'status' => (!$directoryPresent || !$executablePresent)
                    ? 'not-evaluated'
                    : ($executableEvidenceCovered ? 'covered-by-current-executable-evidence' : 'open'),
                'currentEvidence' => $sourceEvidence,
                'evidenceRequired' => 'Run local PHP EPUB reader, a pandoc executable, and paired checked-in .native fixtures against the same EPUB files, keeping parse failures and normalized AST mismatches at zero.',
            ],
            [
                'rank' => 2,
                'id' => 'upstream-haskell-epub-reader-runner-results',
                'status' => 'open',
                'currentEvidence' => 'This harness invokes a pandoc executable and checks the same checked-in native fixtures, but it does not run the upstream Haskell/Tasty process itself.',
                'evidenceRequired' => 'Record reproducible upstream Tests.Readers.EPUB runner results when a Haskell runner is available.',
            ],
        ];
    }

    /**
     * @param list<string> $lines
     * @param array<string, mixed> $report
     * @return list<string>
     */
    private static function appendOrderedRemainingGaps(array $lines, array $report): array
    {
        $gaps = $report['orderedRemainingGaps'] ?? [];
        if (!is_array($gaps) || $gaps === []) {
            return $lines;
        }

        $lines[] = 'orderedRemainingGaps:';
        foreach ($gaps as $gap) {
            if (!is_array($gap)) {
                continue;
            }
            $lines[] = sprintf(
                '%d. %s [%s] current=%s required=%s',
                (int) ($gap['rank'] ?? 0),
                (string) ($gap['id'] ?? 'unknown-gap'),
                (string) ($gap['status'] ?? 'unknown'),
                (string) ($gap['currentEvidence'] ?? ''),
                (string) ($gap['evidenceRequired'] ?? '')
            );
        }

        return $lines;
    }

    private static function percent(int $numerator, int $denominator): ?float
    {
        if ($denominator === 0) {
            return null;
        }

        return round(($numerator / $denominator) * 100, 2);
    }

    private static function formatPercent(mixed $value): string
    {
        if (!is_int($value) && !is_float($value)) {
            return 'n/a';
        }

        return number_format((float) $value, 2) . '%';
    }

    private static function shortJson(mixed $value): string
    {
        try {
            $json = json_encode($value, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR);
        } catch (\JsonException) {
            return gettype($value);
        }

        return strlen($json) > 180 ? substr($json, 0, 177) . '...' : $json;
    }
